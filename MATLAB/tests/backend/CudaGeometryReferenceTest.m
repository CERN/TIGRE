classdef CudaGeometryReferenceTest < backendtest.TestCase
    %CudaGeometryReferenceTest Compare general geometry with CUDA fixtures.

    properties (TestParameter)
        Backend = struct('cpu', "cpu", 'metal', "metal")
        GeometryCase = struct( ...
            'originOffsetStatic', "originOffsetStatic", ...
            'originOffsetPerView', "originOffsetPerView", ...
            'detectorOffsetStatic', "detectorOffsetStatic", ...
            'detectorOffsetPerView', "detectorOffsetPerView", ...
            'corStatic', "corStatic", ...
            'corPerView', "corPerView", ...
            'detectorRoll', "detectorRoll", ...
            'detectorPitch', "detectorPitch", ...
            'detectorYaw', "detectorYaw", ...
            'arbitraryAngles', "arbitraryAngles", ...
            'helical', "helical", ...
            'varyingDistances', "varyingDistances", ...
            'staticDetectorDbt', "staticDetectorDbt", ...
            'combinedCone', "combinedCone", ...
            'combinedParallel', "combinedParallel")
    end

    properties (Constant, Access = private)
        CudaRelativeTolerance = 6e-3
    end

    methods (TestClassSetup)
        function addTigreToPath(testCase)
            matlabRoot = fileparts(fileparts(fileparts( ...
                mfilename('fullpath'))));
            testCase.applyFixture( ...
                matlab.unittest.fixtures.PathFixture(matlabRoot));
            fixtureFolder = fullfile( ...
                matlabRoot, 'tests', 'fixtures');
            testCase.applyFixture( ...
                matlab.unittest.fixtures.PathFixture(fixtureFolder));
        end
    end

    methods (Test, TestTags = {'CUDAReference', 'GeometryReference'})
        function testInterpolatedProjection(testCase, Backend, GeometryCase)
            caseData = CudaGeometryReferenceTest.fixtureCase( ...
                testCase, GeometryCase);
            InitTIGRE('backend', Backend);

            actual = Ax( ...
                caseData.image, caseData.geometry, caseData.angles, ...
                'interpolated');

            testCase.verifyLessThanOrEqual( ...
                CudaGeometryReferenceTest.relativeError( ...
                    caseData.cuda.interpolated, actual), ...
                CudaGeometryReferenceTest.CudaRelativeTolerance);
        end

        function testSiddonProjection(testCase, Backend, GeometryCase)
            caseData = CudaGeometryReferenceTest.fixtureCase( ...
                testCase, GeometryCase);
            InitTIGRE('backend', Backend);

            actual = Ax( ...
                caseData.image, caseData.geometry, caseData.angles, ...
                'Siddon');

            testCase.verifyLessThanOrEqual( ...
                CudaGeometryReferenceTest.relativeError( ...
                    caseData.cuda.siddon, actual), ...
                CudaGeometryReferenceTest.CudaRelativeTolerance);
        end

        function testFdkBackprojection(testCase, Backend, GeometryCase)
            caseData = CudaGeometryReferenceTest.fixtureCase( ...
                testCase, GeometryCase);
            InitTIGRE('backend', Backend);

            actual = Atb( ...
                caseData.cuda.interpolated, ...
                caseData.geometry, caseData.angles, 'FDK');

            testCase.verifyLessThanOrEqual( ...
                CudaGeometryReferenceTest.relativeError( ...
                    caseData.cuda.fdk, actual), ...
                CudaGeometryReferenceTest.CudaRelativeTolerance);
        end

        function testMatchedBackprojection(testCase, Backend, GeometryCase)
            caseData = CudaGeometryReferenceTest.fixtureCase( ...
                testCase, GeometryCase);
            InitTIGRE('backend', Backend);

            actual = Atb( ...
                caseData.cuda.interpolated, ...
                caseData.geometry, caseData.angles, 'matched');

            testCase.verifyLessThanOrEqual( ...
                CudaGeometryReferenceTest.relativeError( ...
                    caseData.cuda.matched, actual), ...
                CudaGeometryReferenceTest.CudaRelativeTolerance);
        end
    end

    methods (Static, Access = private)
        function value = fixtureCase(testCase, geometryCase)
            fixtureFile = fullfile( ...
                fileparts(fileparts(mfilename('fullpath'))), ...
                'fixtures', 'cuda_geometry_reference.mat');
            testCase.assumeTrue(isfile(fixtureFile), ...
                ['CUDA geometry fixture is not present. Generate it on ' ...
                 'the Windows NVIDIA agent using ' ...
                 'runCudaStage2Validation.']);
            loaded = load(fixtureFile, 'fixture');
            validateCudaGeometryReferenceFixture(loaded.fixture);
            value = loaded.fixture.cases.(char(geometryCase));
        end

        function value = relativeError(reference, actual)
            value = norm(double(reference(:) - actual(:))) / ...
                max(norm(double(reference(:))), eps);
        end
    end
end
