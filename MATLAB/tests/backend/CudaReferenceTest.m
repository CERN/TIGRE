classdef CudaReferenceTest < backendtest.TestCase
    %CudaReferenceTest Compare CPU and Metal results with NVIDIA fixtures.

    properties (TestParameter)
        Backend = struct('cpu', "cpu", 'metal', "metal")
    end

    properties (Constant, Access = private)
        CudaRelativeTolerance = 6e-3
    end

    methods (TestClassSetup)
        function addTigreToPath(testCase)
            matlabRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture(matlabRoot));
        end
    end

    methods (Test, TestTags = {'CUDAReference'})
        function testConeProjectionFixture(testCase, Backend)
            fixture = CudaReferenceTest.fixture(testCase);
            InitTIGRE('backend', Backend);

            interpolated = Ax( ...
                fixture.input.coneImage, fixture.input.coneGeometry, ...
                fixture.input.coneAngles, 'interpolated');
            siddon = Ax( ...
                fixture.input.coneImage, fixture.input.coneGeometry, ...
                fixture.input.coneAngles, 'Siddon');

            testCase.verifyLessThanOrEqual( ...
                CudaReferenceTest.relativeError( ...
                    fixture.cuda.coneInterpolated, interpolated), ...
                CudaReferenceTest.CudaRelativeTolerance);
            testCase.verifyLessThanOrEqual( ...
                CudaReferenceTest.relativeError( ...
                    fixture.cuda.coneSiddon, siddon), ...
                CudaReferenceTest.CudaRelativeTolerance);
        end

        function testConeBackprojectionFixture(testCase, Backend)
            fixture = CudaReferenceTest.fixture(testCase);
            InitTIGRE('backend', Backend);

            fdk = Atb( ...
                fixture.cuda.coneInterpolated, fixture.input.coneGeometry, ...
                fixture.input.coneAngles, 'FDK');
            matched = Atb( ...
                fixture.cuda.coneInterpolated, fixture.input.coneGeometry, ...
                fixture.input.coneAngles, 'matched');

            testCase.verifyLessThanOrEqual( ...
                CudaReferenceTest.relativeError(fixture.cuda.coneFdk, fdk), ...
                CudaReferenceTest.CudaRelativeTolerance);
            testCase.verifyLessThanOrEqual( ...
                CudaReferenceTest.relativeError( ...
                    fixture.cuda.coneMatched, matched), ...
                CudaReferenceTest.CudaRelativeTolerance);
        end

        function testParallelFixture(testCase, Backend)
            fixture = CudaReferenceTest.fixture(testCase);
            InitTIGRE('backend', Backend);

            interpolated = Ax( ...
                fixture.input.parallelImage, ...
                fixture.input.parallelGeometry, ...
                fixture.input.parallelAngles, 'interpolated');
            siddon = Ax( ...
                fixture.input.parallelImage, ...
                fixture.input.parallelGeometry, ...
                fixture.input.parallelAngles, 'Siddon');
            reconstruction = Atb( ...
                fixture.cuda.parallelInterpolated, ...
                fixture.input.parallelGeometry, ...
                fixture.input.parallelAngles, 'FDK');

            testCase.verifyLessThanOrEqual( ...
                CudaReferenceTest.relativeError( ...
                    fixture.cuda.parallelInterpolated, interpolated), ...
                CudaReferenceTest.CudaRelativeTolerance);
            testCase.verifyLessThanOrEqual( ...
                CudaReferenceTest.relativeError( ...
                    fixture.cuda.parallelSiddon, siddon), ...
                CudaReferenceTest.CudaRelativeTolerance);
            testCase.verifyLessThanOrEqual( ...
                CudaReferenceTest.relativeError( ...
                    fixture.cuda.parallelAtb, reconstruction), ...
                CudaReferenceTest.CudaRelativeTolerance);
        end

        function testTvFixture(testCase, Backend)
            fixture = CudaReferenceTest.fixture(testCase);
            InitTIGRE('backend', Backend);
            image = fixture.input.tvImage;
            gpuIds = GpuIds();

            tv = minimizeTV(image, 0.05, 2, 'gpuids', gpuIds);
            adaptive = minimizeAwTV( ...
                image, 0.05, 2, -0.01, 'gpuids', gpuIds);
            denoised = im3DDenoise( ...
                image, 'TV', 2, 15, 'gpuids', gpuIds);
            piccs = minimizeTV_prior( ...
                image, fixture.input.prior, 0.05, 2, 0.5, ...
                'gpuids', gpuIds);

            testCase.verifyLessThanOrEqual( ...
                CudaReferenceTest.relativeError(fixture.cuda.minTv, tv), ...
                CudaReferenceTest.CudaRelativeTolerance);
            testCase.verifyLessThanOrEqual( ...
                CudaReferenceTest.relativeError( ...
                    fixture.cuda.adaptiveTv, adaptive), ...
                CudaReferenceTest.CudaRelativeTolerance);
            testCase.verifyLessThanOrEqual( ...
                CudaReferenceTest.relativeError( ...
                    fixture.cuda.denoised, denoised), ...
                CudaReferenceTest.CudaRelativeTolerance);
            testCase.verifyLessThanOrEqual( ...
                CudaReferenceTest.relativeError(fixture.cuda.piccs, piccs), ...
                CudaReferenceTest.CudaRelativeTolerance);
        end
    end

    methods (Static, Access = private)
        function value = fixture(testCase)
            fixtureFile = fullfile( ...
                fileparts(fileparts(mfilename('fullpath'))), ...
                'fixtures', 'cuda_reference.mat');
            testCase.assumeTrue(isfile(fixtureFile), ...
                ['CUDA fixture is not present. Generate it on the Windows ' ...
                 'NVIDIA agent using generateCudaReferenceFixtures.']);
            loaded = load(fixtureFile, 'fixture');
            value = loaded.fixture;
        end

        function value = relativeError(reference, actual)
            value = norm(double(reference(:) - actual(:))) / ...
                max(norm(double(reference(:))), eps);
        end
    end
end
